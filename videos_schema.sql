-- ====================================================================
-- SUPABASE POSTGRESQL SCHEMA FOR VIDEOS (videos)
-- ระบบฐานข้อมูลวิดีโอสร้างสรรค์และการเรียนรู้สำหรับเด็ก (Kids Video Learning)
-- รองรับการทำงานร่วมกับโมดูล videowatchfeatureSupabase โดยตรง
-- ====================================================================

-- 1. สร้างตาราง videos
CREATE TABLE IF NOT EXISTS public.videos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, -- รหัสลำดับ ID
    cat_id INT NOT NULL DEFAULT 1,                           -- รหัสหมวดหมู่ (1=Spark Learning, 2=ABC, 3=Math, ฯลฯ)
    category_name TEXT NOT NULL DEFAULT 'Spark Learning',    -- ชื่อหมวดหมู่ เช่น 'Spark Learning', 'Math Magic', 'ABC & Phonics', 'การ์ตูน'
    vid TEXT UNIQUE NOT NULL,                                -- รหัสอ้างอิงวิดีโอ เช่น 'VID001', 'VID002'
    video_title TEXT NOT NULL,                               -- ชื่อคลิปวิดีโอ
    video_url TEXT NOT NULL,                                 -- ลิงก์สำหรับเปิดดู เช่น 'https://www.youtube.com/watch?v=...'
    video_id TEXT NOT NULL,                                  -- รหัส YouTube Video ID (11 หลัก) เช่น 'AcLn892iPo0'
    video_thumbnail TEXT,                                    -- URL รูปภาพหน้าปกคลิป
    video_duration TEXT DEFAULT '03:00',                     -- ความยาวคลิป เช่น '02:10' หรือจำนวนวินาที
    video_description TEXT,                                  -- คำอธิบายสาระน่ารู้ของวิดีโอ
    video_type TEXT NOT NULL DEFAULT 'youtube',              -- ชนิดของวิดีโอ ('youtube', 'mp4', 'local')
    size TEXT DEFAULT '',                                    -- ขนาดไฟล์ (ถ้ามี)
    total_views BIGINT NOT NULL DEFAULT 0,                   -- จำนวนการรับชม
    date_time TEXT DEFAULT TO_CHAR(NOW(), 'YYYY-MM-DD HH24:MI:SS'), -- วันที่ลงคลิป
    tags TEXT,                                               -- แฮชแท็กคำค้นหา เช่น '#กไก่ #ภาษาไทย #การศึกษา'
    age_rating TEXT DEFAULT '3-7 yrs',                       -- ช่วงวัยที่เหมาะสม เช่น '2-5 yrs', '3-7 yrs', '6-10 yrs'
    language TEXT DEFAULT 'th',                              -- ภาษา เช่น 'th', 'en'
    rating REAL DEFAULT 5.0,                                 -- คะแนนความน่าสนใจ (1.0 - 5.0)
    resolution TEXT DEFAULT '1080p',                         -- ความละเอียดวิดีโอ เช่น '1080p', '720p'
    is_active BOOLEAN NOT NULL DEFAULT true,                 -- สถานะเปิด/ปิดการแสดงผล
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- เพิ่มคำอธิบายตารางและคอลัมน์ (Database Comments)
COMMENT ON TABLE public.videos IS 'ตารางจัดเก็บรายการวิดีโอเพื่อการเรียนรู้สำหรับเด็กและเยาวชน';
COMMENT ON COLUMN public.videos.id IS 'Primary Key ลำดับของวิดีโอ';
COMMENT ON COLUMN public.videos.vid IS 'รหัสเฉพาะสำหรับอ้างอิงวิดีโอ (Unique Code)';
COMMENT ON COLUMN public.videos.video_id IS 'YouTube Video ID 11 ตัวอักษรสำหรับ Inline Player';
COMMENT ON COLUMN public.videos.category_name IS 'หมวดหมู่คลิป สำหรับตัวกรองชิป (All Sparks, Math Magic, ABC & Phonics)';

-- 2. สร้าง Indexes เพื่อความรวดเร็วในการค้นหาและแบ่งหน้า (Pagination)
CREATE INDEX IF NOT EXISTS idx_videos_id ON public.videos(id ASC);
CREATE INDEX IF NOT EXISTS idx_videos_category ON public.videos(category_name);
CREATE INDEX IF NOT EXISTS idx_videos_cat_id ON public.videos(cat_id);
CREATE INDEX IF NOT EXISTS idx_videos_active ON public.videos(is_active);
CREATE INDEX IF NOT EXISTS idx_videos_vid ON public.videos(vid);

-- 3. Trigger อัปเดต updated_at อัตโนมัติเมื่อมีการแก้ไขข้อมูล
CREATE OR REPLACE FUNCTION update_videos_updated_at()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = NOW();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trigger_set_videos_updated_at ON public.videos;
CREATE TRIGGER trigger_set_videos_updated_at
    BEFORE UPDATE ON public.videos
    FOR EACH ROW
    EXECUTE FUNCTION update_videos_updated_at();

-- 4. ตั้งค่าความปลอดภัย Row Level Security (RLS)
ALTER TABLE public.videos ENABLE ROW LEVEL SECURITY;

-- นโยบาย: อนุญาตให้ทุกคน (รวมทั้งผู้ใช้ทั่วไป/Anon) ดึงรายการวิดีโอไปแสดงในแอปได้
DROP POLICY IF EXISTS "Public can view active videos" ON public.videos;
CREATE POLICY "Public can view active videos"
    ON public.videos
    FOR SELECT
    USING (is_active = true);

-- ผู้ดูแลระบบ (Service Role) สามารถ เพิ่ม/ลบ/แก้ไข วิดีโอได้เต็มสิทธิ์
DROP POLICY IF EXISTS "Service role full access on videos" ON public.videos;
CREATE POLICY "Service role full access on videos"
    ON public.videos
    FOR ALL
    TO service_role
    USING (true)
    WITH CHECK (true);

